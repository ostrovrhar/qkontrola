    @staticmethod
    def _relax_layout_min_width(layout):
        # Allow horizontal layouts with many controls to shrink with the dock.
        for i in range(layout.count()):
            item = layout.itemAt(i)
            if item is None:
                continue
            widget = item.widget()
            if widget is None:
                continue
            widget.setMinimumWidth(0)
            policy = widget.sizePolicy()
            # Keep action controls visible; allow only passive/expandable widgets
            # to absorb shrinking pressure.
            if isinstance(
                widget,
                (
                    QtWidgets.QPushButton,
                    QtWidgets.QToolButton,
                    QtWidgets.QRadioButton,
                    QtWidgets.QCheckBox,
                    QtWidgets.QComboBox,
                ),
            ):
                policy.setHorizontalPolicy(QtWidgets.QSizePolicy.Policy.Minimum)
            elif isinstance(widget, QtWidgets.QLineEdit):
                policy.setHorizontalPolicy(QtWidgets.QSizePolicy.Policy.Expanding)
            else:
                policy.setHorizontalPolicy(QtWidgets.QSizePolicy.Policy.Ignored)
            widget.setSizePolicy(policy)


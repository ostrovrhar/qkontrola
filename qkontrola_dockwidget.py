    def _update_attr_pagination_ui(self, total_rows):
        start, end, total_pages, page_index = self._clamp_page(
            total_rows,
            self._attr_page_size,
            self._attr_page_index,
        )
        self._attr_page_index = page_index
        if total_rows <= 0:
            self.attr_range_label.setText("0-0 / 0")
        else:
            self.attr_range_label.setText(f"{start + 1}-{end} / {total_rows}")
        has_prev = total_pages > 1 and page_index > 0
        has_next = total_pages > 1 and page_index < total_pages - 1
        enabled = self.attr_page_size_combo.isEnabled()
        self.attr_first_btn.setEnabled(enabled and has_prev)
        self.attr_prev_btn.setEnabled(enabled and has_prev)
        self.attr_next_btn.setEnabled(enabled and has_next)
        self.attr_last_btn.setEnabled(enabled and has_next)
        return start, end


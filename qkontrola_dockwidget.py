    @staticmethod
    def _clamp_page(total_rows, page_size, page_index):
        if page_size <= 0:
            page_size = 250
        if total_rows <= 0:
            return 0, 0, 0, 0
        total_pages = (total_rows + page_size - 1) // page_size
        page_index = max(0, min(page_index, total_pages - 1))
        start = page_index * page_size
        end = min(total_rows, start + page_size)
        return start, end, total_pages, page_index

    def _on_attr_page_size_changed(self, text):
        try:
            self._attr_page_size = max(1, int(text))
        except ValueError:
            self._attr_page_size = 250

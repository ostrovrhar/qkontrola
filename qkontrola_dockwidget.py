    def _focus_error_feature(self, row, _column):
        self._clear_topology_gap_highlight()
        if row < 0 or row >= len(self._visible_errors):
            return
        err = self._visible_errors[row]
        fid = err.get("fid")
        if fid is None:
            return
        layer = self.layer_combo.currentLayer()
        if layer is None:
            return
        if self.iface is None:
            return

        layer.selectByIds([fid])
        request = QgsFeatureRequest().setFilterFid(fid)
        feature = next(layer.getFeatures(request), None)
        if feature is None or not feature.hasGeometry():
            return
        extent = feature.geometry().boundingBox()
        if extent.isEmpty():
            return
        if extent.width() == 0 and extent.height() == 0:
            extent.grow(5.0)
        else:
            extent.grow(max(extent.width(), extent.height()) * 0.25)
        self.iface.mapCanvas().setExtent(extent)
        self.iface.mapCanvas().refresh()

    def _focus_topology_feature(self, row, _column):
        if row < 0 or row >= len(self._visible_topology_errors):
            return
        err = self._visible_topology_errors[row]
        fid = err.get("fid")
        if fid is None:
            return
        layer = self.layer_combo.currentLayer()
        if layer is None or self.iface is None:
            return
        layer.selectByIds([fid])
        gap_wkt = (err.get("gap_wkt") or "").strip()
        if gap_wkt:
            self._highlight_gap_geometry(gap_wkt)
            return
        self._clear_topology_gap_highlight()
        request = QgsFeatureRequest().setFilterFid(fid)
        feature = next(layer.getFeatures(request), None)
        if feature is None or not feature.hasGeometry():
            return
        extent = feature.geometry().boundingBox()
        if extent.isEmpty():
            return
        if extent.width() == 0 and extent.height() == 0:
            extent.grow(5.0)
        else:
            extent.grow(max(extent.width(), extent.height()) * 0.25)
        self.iface.mapCanvas().setExtent(extent)
        self.iface.mapCanvas().refresh()

    def _clear_topology_gap_highlight(self):
        rb = getattr(self, "_topology_gap_rubber_band", None)
        if rb is None:
            return
        try:
            canvas = self.iface.mapCanvas() if self.iface is not None else None
            if canvas is not None and canvas.scene() is not None:
                canvas.scene().removeItem(rb)
        except Exception:
            pass
        self._topology_gap_rubber_band = None

    def _highlight_gap_geometry(self, gap_wkt):
        if not gap_wkt or self.iface is None:
            return
        canvas = self.iface.mapCanvas()
        if canvas is None:
            return
        try:
            from qgis.core import QgsGeometry
            from qgis.gui import QgsRubberBand
            from qgis.PyQt.QtGui import QColor
        except Exception:
            return

        gap_geom = QgsGeometry.fromWkt(gap_wkt)
        if gap_geom is None or gap_geom.isNull():
            return
        self._clear_topology_gap_highlight()

        rb = QgsRubberBand(canvas, Qgis.GeometryType.Polygon)
        rb.setColor(QColor(220, 38, 38, 220))
        rb.setFillColor(QColor(220, 38, 38, 70))
        rb.setWidth(2)
        rb.setToGeometry(gap_geom, None)
        self._topology_gap_rubber_band = rb

        extent = gap_geom.boundingBox()
        if not extent.isEmpty():
            if extent.width() == 0 and extent.height() == 0:
                extent.grow(5.0)
            else:
                extent.grow(max(extent.width(), extent.height()) * 0.25)
            canvas.setExtent(extent)
        canvas.refresh()


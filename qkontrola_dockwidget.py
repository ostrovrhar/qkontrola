class AttributeValidationTask(QgsTask):
    def __init__(
        self,
        layer,
        rules,
        load_errors,
        run_attributes=True,
        topology_options=None,
        conditional_rules=None,
    ):
        super().__init__("QKontrola: atributna kontrola", QgsTask.Flag.CanCancel)
        self.layer = layer
        self.rules = rules
        self.load_errors = load_errors
        self.run_attributes = run_attributes
        self.topology_options = topology_options or {}
        self.conditional_rules = conditional_rules or []
        self.result_data = None
        self.error_message = ""

    @staticmethod
    def _safe_value(value):
        if value is None or (isinstance(value, QVariant) and value.isNull()):
            return "NULL"
        return str(value).strip()

    @staticmethod
    def _is_empty(value, empty_markers=None):
        if value is None or (isinstance(value, QVariant) and value.isNull()):
            return True
        s = str(value).strip()
        if s == "":
            return True
        if empty_markers:
            for marker in empty_markers.split("|"):
                marker = marker.strip()
                if marker and s == marker:
                    return True
        return False

    @staticmethod
    def _match_token(token, value_str):
        low = token.lower()
        if low.startswith("regex(") and token.endswith(")"):
            regex_body = token[6:-1].strip()
            try:
                return bool(re.match(regex_body, value_str))
            except re.error:
                return False
        if low in {"črke", "crke"}:
            return bool(re.match(r"^[A-ZČŠŽ][A-Za-zČŠŽčšž ]{1,}$", value_str))
        if low in {"črke_i", "crke_i"}:
            return bool(re.match(r"^[A-Za-zČŠŽčšž][A-Za-zČŠŽčšž ]{1,}$", value_str))
        if low in {"brez_številk", "brez_stevilk"}:
            return bool(re.match(r"^[^0-9]+$", value_str))
        if low in {"prvi_znak_ni_številka", "prvi_znak_ni_stevilka"}:
            return bool(re.match(r"^[^0-9].*$", value_str))
        if low in {"številke", "stevilke"}:
            return bool(re.match(r"^[-]?[0-9]+([.][0-9]+)?$", value_str))
        if token == "********":
            return bool(re.match(r"^[0-9]{8}$", value_str))
        pref = token
        if low.startswith("z") and token.endswith("-") and len(token) > 2:
            pref = token[1:]
        if pref.endswith("-"):
            escaped = re.escape(pref)
            return bool(re.match(escaped + r".*$", value_str))
        if re.fullmatch(r"-?\d+(\.\d+)?", token):
            return value_str == token
        return value_str == token

    @staticmethod
    def _check_rule(value, rule_type, param):
        is_empty = AttributeValidationTask._is_empty(value)
        if rule_type == "ne sme biti prazno":
            return not AttributeValidationTask._is_empty(value, param)
        if rule_type == "mora biti prazno":
            return AttributeValidationTask._is_empty(value, param)
        if is_empty:
            if rule_type == "dovoljene vrednosti":
                tokens = [t.strip() for t in param.split("|") if t.strip()]
                return "prazno" in tokens
            return False
        if rule_type == "regex":
            try:
                return bool(re.match(param, str(value).strip()))
            except re.error:
                return False
        if rule_type == "dovoljene vrednosti":
            tokens = [t.strip() for t in param.split("|") if t.strip()]
            s = str(value).strip()
            for token in tokens:
                if token == "prazno":
                    continue
                if AttributeValidationTask._match_token(token, s):
                    return True
            return False
        return True

    NORMALIZED_TYPES = {
        "integer": QVariant.Int,
        "int": QVariant.Int,
        "double": QVariant.Double,
        "real": QVariant.Double,
        "string": QVariant.String,
        "text": QVariant.String,
        "date": QVariant.Date,
        "datetime": QVariant.DateTime,
        "boolean": QVariant.Bool,
        "bool": QVariant.Bool,
    }

    @staticmethod
    def _check_field_type(actual_field, expected_type_str):
        if not expected_type_str:
            return True, ""
        expected_type_str = expected_type_str.strip().lower()
        expected_qvt = AttributeValidationTask.NORMALIZED_TYPES.get(expected_type_str)
        if expected_qvt is None:
            return False, f"Neznan tip: {expected_type_str}"
        actual_type = actual_field.type()
        if actual_type == expected_qvt:
            return True, ""
        if expected_qvt == QVariant.Int and actual_type in (
            QVariant.Int,
            QVariant.UInt,
            QVariant.LongLong,
            QVariant.ULongLong,
        ):
            return True, ""
        return False, f"Dejanski tip: {actual_field.typeName()}"

    @staticmethod
    def _is_line_layer(layer):
        try:
            geom_type = layer.geometryType()
        except Exception:
            return False
        try:
            if geom_type == Qgis.GeometryType.Line:
                return True
        except Exception:
            pass
        try:
            return int(geom_type) == 1
        except Exception:
            return "line" in str(geom_type).lower()

    @staticmethod
    def _is_polygon_layer(layer):
        try:
            geom_type = layer.geometryType()
        except Exception:
            return False
        try:
            if geom_type == Qgis.GeometryType.Polygon:
                return True
        except Exception:
            pass
        try:
            return int(geom_type) == 2
        except Exception:
            return "polygon" in str(geom_type).lower()

    @staticmethod
    def _point_key(point, precision=8):
        return (round(float(point.x()), precision), round(float(point.y()), precision))

    @classmethod
    def _line_endpoints(cls, geom):
        endpoints = []
        try:
            if geom.isMultipart():
                parts = geom.asMultiPolyline()
                for part in parts:
                    if len(part) >= 2:
                        start_key = cls._point_key(part[0])
                        end_key = cls._point_key(part[-1])
                        if start_key == end_key:
                            # Closed part has no dangling endpoints for dangle/pseudo checks.
                            continue
                        endpoints.append((start_key, end_key))
            else:
                line = geom.asPolyline()
                if len(line) >= 2:
                    start_key = cls._point_key(line[0])
                    end_key = cls._point_key(line[-1])
                    if start_key != end_key:
                        endpoints.append((start_key, end_key))
        except Exception:
            return []
        return endpoints

    @staticmethod
    def _multipart_has_multiple_parts(geom):
        """Return True only when geometry has more than one actual part."""
        if geom is None or geom.isNull():
            return False
        try:
            collection = geom.asGeometryCollection()
            if collection:
                return len(collection) > 1
        except Exception:
            pass
        try:
            const_geom = geom.constGet()
            if const_geom is not None:
                return int(const_geom.partCount()) > 1
        except Exception:
            pass
        return False

    def run(self):
        try:
            errors = list(self.load_errors)
            topology_errors = []
            field_map = {f.name(): f for f in self.layer.fields()}
            attr_stats_by_attr = {}
            attr_stats_order = []
            for rule in self.rules:
                if rule.attribute_name not in attr_stats_by_attr:
                    qfield = field_map.get(rule.attribute_name)
                    exists = qfield is not None
                    type_ok = True
                    type_msg = ""
                    if exists and rule.field_type:
                        type_ok, type_msg = AttributeValidationTask._check_field_type(
                            qfield, rule.field_type
                        )
                    stat = {
                        "attribute": rule.attribute_name,
                        "rule_type": rule.rule_type,
                        "param": rule.param,
                        "field_type": rule.field_type,
                        "exists": exists,
                        "type_ok": type_ok,
                        "type_msg": type_msg,
                        "checked": 0,
                        "failed": 0,
                    }
                    attr_stats_by_attr[rule.attribute_name] = stat
                    attr_stats_order.append(rule.attribute_name)
                    if not exists:
                        errors.append(
                            {
                                "fid": None,
                                "attribute": rule.attribute_name,
                                "value": "",
                                "message": "Atribut ne obstaja v sloju.",
                                "expr": "",
                                "_schema": True,
                            }
                        )
                    elif not type_ok:
                        errors.append(
                            {
                                "fid": None,
                                "attribute": rule.attribute_name,
                                "value": qfield.typeName(),
                                "message": (
                                    f"Tip atributa se ne ujema (pričakovano: {rule.field_type}, "
                                    f"dejansko: {qfield.typeName()})."
                                ),
                                "expr": "",
                                "_schema": True,
                            }
                        )

            cond_stats = [
                {
                    "target": r.target,
                    "rule_type": r.rule_type,
                    "param": r.param,
                    "cond_field": r.cond_field,
                    "cond_value": r.cond_value,
                    "checked": 0,
                    "failed": 0,
                    "target_exists": True,
                    "cond_field_exists": True,
                }
                for r in self.conditional_rules
            ]

            if cond_stats:
                for i, cs in enumerate(cond_stats):
                    r = self.conditional_rules[i]
                    cs["target_exists"] = r.target in field_map
                    cs["cond_field_exists"] = r.cond_field in field_map

            needed_attrs = list(attr_stats_by_attr.keys())
            for cr in self.conditional_rules:
                if cr.target not in needed_attrs:
                    needed_attrs.append(cr.target)
                if cr.cond_field not in needed_attrs:
                    needed_attrs.append(cr.cond_field)
            request = QgsFeatureRequest()
            if self.run_attributes and needed_attrs:
                request.setSubsetOfAttributes(needed_attrs, self.layer.fields())

            run_topology = bool(self.topology_options.get("enabled", False))
            check_invalid = bool(self.topology_options.get("check_invalid", False))
            check_multipart = bool(self.topology_options.get("check_multipart", False))
            check_duplicates = bool(
                self.topology_options.get("check_duplicates", False)
            )
            check_dangles = bool(self.topology_options.get("check_dangles", False))
            check_pseudos = bool(self.topology_options.get("check_pseudos", False))
            check_overlap = bool(self.topology_options.get("check_overlap", False))
            check_gaps = bool(self.topology_options.get("check_gaps", False))
            line_layer = self._is_line_layer(self.layer)
            polygon_layer = self._is_polygon_layer(self.layer)

            if not run_topology:
                try:
                    request.setFlags(Qgis.FeatureRequestFlag.NoGeometry)
                except Exception:
                    try:
                        request.setFlags(QgsFeatureRequest.Flag.NoGeometry)
                    except Exception:
                        pass

            topo_stats = {
                "enabled": run_topology,
                "run_attributes": self.run_attributes,
                "check_invalid": check_invalid,
                "check_multipart": check_multipart,
                "check_duplicates": check_duplicates,
                "check_dangles": check_dangles,
                "check_pseudos": check_pseudos,
                "check_overlap": check_overlap,
                "check_gaps": check_gaps,
                "line_layer": line_layer,
                "polygon_layer": polygon_layer,
                "checked_features": 0,
                "invalid_errors": 0,
                "multipart_errors": 0,
                "duplicate_errors": 0,
                "dangle_errors": 0,
                "pseudo_errors": 0,
                "overlap_errors": 0,
                "gap_errors": 0,
            }

            seen_geometries = {}
            endpoint_counts = {}
            endpoint_fids = {}
            polygon_geoms = {}
            polygon_index = (
                QgsSpatialIndex()
                if run_topology and polygon_layer and (check_overlap or check_gaps)
                else None
            )

            total_features = self.layer.featureCount()
            if total_features is None or total_features < 0:
                total_features = 0

            processed = 0
            for feature in self.layer.getFeatures(request):
                if self.isCanceled():
                    self.error_message = "Prekinjeno."
                    return False

                processed += 1

                if run_topology and (
                    check_invalid
                    or check_multipart
                    or check_duplicates
                    or check_dangles
                    or check_pseudos
                    or check_overlap
                    or check_gaps
                ):
                    topo_stats["checked_features"] += 1
                    geom = feature.geometry()
                    has_geom = geom is not None and not geom.isNull()
                    fid_int = int(feature.id())

                    if check_multipart and has_geom:
                        if self._multipart_has_multiple_parts(geom):
                            topo_stats["multipart_errors"] += 1
                            topology_errors.append(
                                {
                                    "fid": fid_int,
                                    "check": "Must not have multipart geometries",
                                    "message": "Geometrija je večdelna (multipart).",
                                }
                            )

                    if check_invalid:
                        invalid = False
                        details = "Geometrija je neveljavna."
                        if not has_geom:
                            invalid = True
                            details = "Objekt nima geometrije."
                        else:
                            try:
                                invalid = not geom.isGeosValid()
                            except Exception:
                                invalid = False
                            if invalid:
                                try:
                                    geom_errors = geom.validateGeometry()
                                    if geom_errors:
                                        details = str(geom_errors[0])
                                except Exception:
                                    pass

                        if invalid:
                            topo_stats["invalid_errors"] += 1
                            topology_errors.append(
                                {
                                    "fid": fid_int,
                                    "check": "Must not have invalid geometry",
                                    "message": details,
                                }
                            )

                    if check_duplicates and has_geom:
                        try:
                            geom_key = bytes(geom.asWkb())
                        except Exception:
                            geom_key = None
                        if geom_key:
                            first_fid = seen_geometries.get(geom_key)
                            if first_fid is None:
                                seen_geometries[geom_key] = fid_int
                            else:
                                topo_stats["duplicate_errors"] += 1
                                topology_errors.append(
                                    {
                                        "fid": fid_int,
                                        "check": "Must not have duplicates",
                                        "message": f"Podvojena geometrija (enako kot FID {first_fid}).",
                                    }
                                )

                    if (check_dangles or check_pseudos) and line_layer and has_geom:
                        ends = self._line_endpoints(geom)
                        if ends:
                            for start_key, end_key in ends:
                                endpoint_counts[start_key] = (
                                    endpoint_counts.get(start_key, 0) + 1
                                )
                                endpoint_counts[end_key] = (
                                    endpoint_counts.get(end_key, 0) + 1
                                )
                                endpoint_fids.setdefault(start_key, set()).add(fid_int)
                                endpoint_fids.setdefault(end_key, set()).add(fid_int)

                    if polygon_index is not None and has_geom:
                        polygon_geoms[fid_int] = geom
                        try:
                            idx_feat = QgsFeature()
                            idx_feat.setId(fid_int)
                            idx_feat.setGeometry(geom)
                            polygon_index.addFeature(idx_feat)
                        except Exception:
                            pass

                for rule in self.rules:
                    stat = attr_stats_by_attr.get(rule.attribute_name)
                    if stat is None:
                        continue
                    stat["checked"] += 1
                    raw = feature[rule.attribute_name]
                    if not self._check_rule(raw, rule.rule_type, rule.param):
                        stat["failed"] += 1
                        errors.append(
                            {
                                "fid": int(feature.id()),
                                "attribute": rule.attribute_name,
                                "value": self._safe_value(raw),
                                "message": "Vrednost ne ustreza pravilu.",
                                "expr": f"{rule.rule_type}: {rule.param}",
                            }
                        )

                for idx, crel in enumerate(self.conditional_rules):
                    cond_raw = feature[crel.cond_field]
                    cond_str = self._safe_value(cond_raw)
                    condition_hit = False
                    if crel.negated:
                        # Negated: rule applies when cond_field is NOT in cond_values
                        if cond_str == "NULL":
                            condition_hit = True
                        else:
                            condition_hit = cond_str not in crel.cond_values
                    else:
                        # Positive: rule applies when cond_field IS in cond_values
                        if cond_str == "NULL":
                            condition_hit = False
                        else:
                            condition_hit = cond_str in crel.cond_values
                    if not condition_hit:
                        continue
                    cond_stats[idx]["checked"] += 1
                    target_raw = feature[crel.target]
                    if not self._check_rule(target_raw, crel.rule_type, crel.param):
                        cond_stats[idx]["failed"] += 1
                        errors.append(
                            {
                                "fid": int(feature.id()),
                                "attribute": crel.target,
                                "value": self._safe_value(target_raw),
                                "message": (
                                    f"Pogoj: {crel.cond_field} pri {crel.cond_value} → "
                                    f"{crel.rule_type}: {crel.param}"
                                ),
                                "expr": (
                                    f"pogoj: {crel.cond_field} = {crel.cond_value} → "
                                    f"{crel.rule_type}: {crel.param}"
                                ),
                                "_cond": True,
                            }
                        )

                if total_features > 0 and processed % 500 == 0:
                    self.setProgress(min(85.0, (processed / total_features) * 85.0))

            if run_topology and line_layer and (check_dangles or check_pseudos):
                if check_dangles:
                    for node, endpoint_total in endpoint_counts.items():
                        if endpoint_total != 1:
                            continue
                        fids_at_node = endpoint_fids.get(node, set())
                        if not fids_at_node:
                            continue
                        fid_ref = int(next(iter(fids_at_node)))
                        topo_stats["dangle_errors"] += 1
                        topology_errors.append(
                            {
                                "fid": fid_ref,
                                "check": "Must not have dangles",
                                "message": f"Dangle konec na ({node[0]}, {node[1]}).",
                            }
                        )

                if check_pseudos:
                    # Count pseudo violations by pseudo-node (not by feature), closer to QGIS topology checker behavior.
                    for node, endpoint_total in endpoint_counts.items():
                        if endpoint_total != 2:
                            continue
                        fids_at_node = endpoint_fids.get(node, set())
                        if not fids_at_node:
                            continue
                        fid_list = sorted(fids_at_node)
                        fid_a = int(fid_list[0])
                        fid_b = int(fid_list[1]) if len(fid_list) > 1 else fid_a
                        topo_stats["pseudo_errors"] += 1
                        topology_errors.append(
                            {
                                "fid": fid_a,
                                "check": "Must not have pseudos",
                                "message": (
                                    f"Pseudo vozlišče med FID {fid_a} in FID {fid_b} "
                                    f"na ({node[0]}, {node[1]})."
                                ),
                            }
                        )

            if run_topology:
                self.setProgress(88.0)

            if (
                run_topology
                and polygon_layer
                and polygon_index is not None
                and check_overlap
            ):
                total_polygons = float(max(1, len(polygon_geoms)))
                for idx, (fid_int, geom) in enumerate(polygon_geoms.items()):
                    if self.isCanceled():
                        self.error_message = "Prekinjeno."
                        return False
                    if idx % 500 == 0:
                        self.setProgress(min(94.0, 91.0 + (idx / total_polygons) * 3.0))
                    for other_fid in polygon_index.intersects(geom.boundingBox()):
                        if other_fid <= fid_int:
                            continue
                        other_geom = polygon_geoms.get(int(other_fid))
                        if other_geom is None:
                            continue
                        try:
                            inter = geom.intersection(other_geom)
                            has_overlap = (
                                inter is not None
                                and (not inter.isNull())
                                and inter.area() > 0.0
                            )
                        except Exception:
                            has_overlap = False
                        if has_overlap:
                            topo_stats["overlap_errors"] += 1
                            topology_errors.append(
                                {
                                    "fid": fid_int,
                                    "check": "Must not overlap",
                                    "message": f"Prekrivanje z objektom FID {other_fid}.",
                                }
                            )
                            topology_errors.append(
                                {
                                    "fid": int(other_fid),
                                    "check": "Must not overlap",
                                    "message": f"Prekrivanje z objektom FID {fid_int}.",
                                }
                            )

            if run_topology and polygon_layer and polygon_geoms and check_gaps:
                # Dissolve all polygons and detect gaps as interior-ring polygons.
                try:
                    union_geom = QgsGeometry.unaryUnion(list(polygon_geoms.values()))
                    if union_geom is not None and not union_geom.isNull():
                        self.setProgress(95.0)
                        gap_parts = []
                        try:
                            no_holes = union_geom.removeInteriorRings(-1)
                            gaps_geom = no_holes.difference(union_geom)
                        except Exception:
                            gaps_geom = None

                        if gaps_geom is not None and not gaps_geom.isNull():
                            try:
                                if gaps_geom.isMultipart():
                                    for part in gaps_geom.asGeometryCollection():
                                        if part is None or part.isNull():
                                            continue
                                        try:
                                            if part.area() <= 0:
                                                continue
                                        except Exception:
                                            pass
                                        gap_parts.append(part)
                                else:
                                    if gaps_geom.area() > 0:
                                        gap_parts.append(gaps_geom)
                            except Exception:
                                pass

                        if gap_parts:
                            topo_stats["gap_errors"] = len(gap_parts)
                            for gap_idx, gap_geom in enumerate(gap_parts):
                                if self.isCanceled():
                                    self.error_message = "Prekinjeno."
                                    return False
                                if gap_idx % max(1, len(gap_parts) // 20) == 0:
                                    self.setProgress(
                                        min(
                                            99.0,
                                            96.0 + (gap_idx / len(gap_parts)) * 3.0,
                                        )
                                    )

                                try:
                                    gap_boundary = gap_geom.boundary()
                                except Exception:
                                    gap_boundary = None

                                if polygon_index is not None:
                                    candidate_fids = polygon_index.intersects(
                                        gap_geom.boundingBox()
                                    )
                                else:
                                    candidate_fids = polygon_geoms.keys()

                                neighbor_scores = []
                                fallback_neighbors = []
                                for candidate_fid in candidate_fids:
                                    candidate_fid = int(candidate_fid)
                                    candidate_geom = polygon_geoms.get(candidate_fid)
                                    if candidate_geom is None:
                                        continue
                                    try:
                                        shared = candidate_geom.boundary().intersection(
                                            gap_boundary
                                        )
                                        shared_len = (
                                            float(shared.length())
                                            if shared is not None
                                            and not shared.isNull()
                                            else 0.0
                                        )
                                    except Exception:
                                        shared_len = 0.0

                                    if shared_len > 0.0:
                                        neighbor_scores.append(
                                            (candidate_fid, shared_len)
                                        )
                                    else:
                                        # Fallback: topology relation exists, but shared boundary
                                        # length could not be computed robustly.
                                        try:
                                            related = candidate_geom.touches(
                                                gap_geom
                                            ) or candidate_geom.intersects(gap_geom)
                                        except Exception:
                                            related = False
                                        if related:
                                            fallback_neighbors.append(
                                                (candidate_fid, 0.0)
                                            )

                                gap_area = 0.0
                                try:
                                    gap_area = float(gap_geom.area())
                                except Exception:
                                    gap_area = 0.0

                                # One gap can have multiple neighbors; report each actual neighbor.
                                if not neighbor_scores and fallback_neighbors:
                                    neighbor_scores = fallback_neighbors
                                if not neighbor_scores:
                                    # Last resort: keep gap visible in topology table and status counts.
                                    try:
                                        any_fid = int(next(iter(candidate_fids)))
                                    except Exception:
                                        try:
                                            any_fid = int(
                                                next(iter(polygon_geoms.keys()))
                                            )
                                        except Exception:
                                            any_fid = None
                                    if any_fid is not None:
                                        neighbor_scores = [(any_fid, 0.0)]
                                neighbor_scores.sort(
                                    key=lambda item: (-item[1], item[0])
                                )
                                for neighbor_fid, _shared_len in neighbor_scores:
                                    topology_errors.append(
                                        {
                                            "fid": int(neighbor_fid),
                                            "check": "Must not have gaps",
                                            "message": f"Najdena vrzel (gap), površina {gap_area:.3f}.",
                                            "gap_wkt": gap_geom.asWkt(),
                                        }
                                    )
                except Exception:
                    pass

            if total_features <= 0:
                total_features = processed

            error_count = sum(1 for e in errors if e.get("fid") is not None)
            cond_rule_count = len(self.conditional_rules)
            self.result_data = {
                "total_features": total_features,
                "rule_count": len(self.rules),
                "conditional_rule_count": cond_rule_count,
                "run_attributes": self.run_attributes,
                "error_count": error_count,
                "errors": errors,
                "attr_stats": [attr_stats_by_attr[name] for name in attr_stats_order],
                "topology_errors": topology_errors,
                "topology_stats": topo_stats,
                "cond_stats": cond_stats,
            }
            self.setProgress(100.0)
            return True
        except Exception as exc:  # pragma: no cover - runtime safety
            self.error_message = str(exc)
            return False


class GpkgExportTask(QgsTask):
    def __init__(
        self,
        layer_source,
        layer_provider,
        layer_crs_wkt,
        transform_context,
        error_rows,
        error_type,
        output_path,
    ):
        super().__init__("QKontrola: izvoz napak v GPKG", QgsTask.Flag.CanCancel)
        self.layer_source = layer_source
        self.layer_provider = layer_provider
        self.layer_crs_wkt = layer_crs_wkt
        self.transform_context = transform_context
        self.error_rows = list(error_rows)
        self.error_type = error_type
        self.output_path = output_path
        self.result_data = None
        self.error_message = ""

    @staticmethod
    def _no_geometry_wkb(wkb_type):
        try:
            return wkb_type == Qgis.WkbType.NoGeometry
        except Exception:
            return wkb_type == QgsWkbTypes.NoGeometry

    @staticmethod
    def _memory_geom_token(wkb_type):
        try:
            geom_family = QgsWkbTypes.geometryType(wkb_type)
            is_multi = QgsWkbTypes.isMultiType(wkb_type)
        except Exception:
            return ""

        if geom_family == Qgis.GeometryType.Point:
            return "MultiPoint" if is_multi else "Point"
        if geom_family == Qgis.GeometryType.Line:
            return "MultiLineString" if is_multi else "LineString"
        if geom_family == Qgis.GeometryType.Polygon:
            return "MultiPolygon" if is_multi else "Polygon"
        return ""

    def run(self):
        try:
            src_layer = QgsVectorLayer(
                self.layer_source, "qkontrola_export_src", self.layer_provider
            )
            if not src_layer.isValid():
                self.error_message = "Virni sloj za izvoz ni veljaven."
                return False

            source_fids = sorted(
                {int(e["fid"]) for e in self.error_rows if e.get("fid") is not None}
            )
            if not source_fids:
                self.error_message = "Ni veljavnih FID za izvoz."
                return False

            source_features = {}
            total_fids = len(source_fids)
            request = QgsFeatureRequest().setFilterFids(source_fids)
            for idx, feat in enumerate(src_layer.getFeatures(request), start=1):
                if self.isCanceled():
                    self.error_message = "Prekinjeno."
                    return False
                source_features[int(feat.id())] = feat
                if idx % 200 == 0 or idx == total_fids:
                    self.setProgress(5.0 + (idx / total_fids) * 20.0)

            geom_token = self._memory_geom_token(src_layer.wkbType())
            if not geom_token:
                self.error_message = (
                    "Ni bilo mogoče ustvariti začasnega sloja z geometrijo za izvoz."
                )
                return False
            mem_layer = QgsVectorLayer(geom_token, "qkontrola_errors", "memory")
            if not mem_layer.isValid() or self._no_geometry_wkb(mem_layer.wkbType()):
                self.error_message = (
                    "Ni bilo mogoče ustvariti začasnega sloja z geometrijo za izvoz."
                )
                return False
            target_crs = src_layer.crs()
            if self.layer_crs_wkt:
                crs_from_layer = QgsCoordinateReferenceSystem()
                if crs_from_layer.createFromWkt(self.layer_crs_wkt):
                    target_crs = crs_from_layer
            if target_crs.isValid():
                mem_layer.setCrs(target_crs)

            provider = mem_layer.dataProvider()

            fields = QgsFields()
            fields.append(QgsField("FID_SRC", QVariant.Int))
            if self.error_type == "attribute":
                fields.append(QgsField("ATTRIBUTE", QVariant.String, "", 80))
                fields.append(QgsField("VALUE", QVariant.String, "", 120))
                fields.append(QgsField("MESSAGE", QVariant.String, "", 254))
                fields.append(QgsField("EXPR", QVariant.String, "", 254))
            else:
                fields.append(QgsField("CHECK", QVariant.String, "", 120))
                fields.append(QgsField("MESSAGE", QVariant.String, "", 254))
            provider.addAttributes(fields)
            mem_layer.updateFields()

            out_features = []
            missing_geom_count = 0
            total_rows = len(self.error_rows)
            for idx, err in enumerate(self.error_rows, start=1):
                if self.isCanceled():
                    self.error_message = "Prekinjeno."
                    return False

                fid = err.get("fid")
                if fid is None:
                    continue
                src_feature = source_features.get(int(fid))
                if src_feature is None or not src_feature.hasGeometry():
                    missing_geom_count += 1
                    continue

                out = QgsFeature(mem_layer.fields())
                out.setGeometry(src_feature.geometry())
                if self.error_type == "attribute":
                    out.setAttributes(
                        [
                            int(fid),
                            str(err.get("attribute", "")),
                            str(err.get("value", "")),
                            str(err.get("message", "")),
                            str(err.get("expr", "")),
                        ]
                    )
                else:
                    out.setAttributes(
                        [
                            int(fid),
                            str(err.get("check", "")),
                            str(err.get("message", "")),
                        ]
                    )
                out_features.append(out)

                if idx % 500 == 0 or idx == total_rows:
                    self.setProgress(30.0 + (idx / max(1, total_rows)) * 60.0)

            if not out_features:
                self.error_message = "Napake obstajajo, vendar ni geometrij za izvoz."
                return False

            provider.addFeatures(out_features)
            mem_layer.updateExtents()

            options = QgsVectorFileWriter.SaveVectorOptions()
            options.driverName = "GPKG"
            options.layerName = "qkontrola_errors"
            options.fileEncoding = "UTF-8"
            self.setProgress(95.0)
            writer_result = QgsVectorFileWriter.writeAsVectorFormatV3(
                mem_layer,
                self.output_path,
                self.transform_context,
                options,
            )
            if isinstance(writer_result, tuple):
                result = writer_result[0]
                error_message = writer_result[1] if len(writer_result) > 1 else ""
            else:
                result = writer_result
                error_message = ""

            if result != QgsVectorFileWriter.WriterError.NoError:
                self.error_message = error_message or "Neznana napaka pri zapisu GPKG."
                return False

            self.result_data = {
                "path": self.output_path,
                "missing_geom_count": missing_geom_count,
                "exported_count": len(out_features),
            }
            self.setProgress(100.0)
            return True
        except Exception as exc:  # pragma: no cover - runtime safety
            self.error_message = str(exc)
            return False



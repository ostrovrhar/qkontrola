    def _render_visible_error_tab(self):
        current = self.tabs.currentIndex()
        if current == self.attr_errors_tab_index:
            if self._attr_table_rendered:
                self._topology_render_done = True
                self._errors_render_done = True
                self._finish_post_render_if_ready()
                return
            self._errors_render_done = False
            self._render_errors_table(self._pending_attr_table_data)
            self._topology_render_done = True
            self._finish_post_render_if_ready()
            return
        if current == self.topology_errors_tab_index:
            if self._topology_table_rendered:
                self._errors_render_done = True
                self._topology_render_done = True
                self._finish_post_render_if_ready()
                return
            self._topology_render_done = False
            self._render_topology_table(self._pending_topology_table_data)
            self._errors_render_done = True
            self._finish_post_render_if_ready()
            return

        # If we stay on report tab, skip expensive table rendering for now.
        self._errors_render_done = True
        self._topology_render_done = True
        self._finish_post_render_if_ready()

    def _render_errors_table(self, errors):
        self._errors = errors
        total = len(errors)
        start, end = self._update_attr_pagination_ui(total)
        self._visible_errors = list(errors[start:end])
        self._pending_errors_render = list(self._visible_errors)
        self._errors_render_index = 0
        self.errors_table.clearContents()
        self.errors_table.setRowCount(len(self._pending_errors_render))
        self.attr_table_info_label.setText("Atributne napake")
        if not self._pending_errors_render:
            self._attr_table_rendered = True
            self._errors_render_done = True
            self._finish_post_render_if_ready()
            return
        QTimer.singleShot(0, self._render_errors_table_batch)

    def _render_errors_table_batch(self):
        total = len(self._pending_errors_render)
        if total == 0:
            return

        start = self._errors_render_index
        end = min(total, start + self._render_batch_size)
        self.errors_table.setUpdatesEnabled(False)
        for row in range(start, end):
            err = self._pending_errors_render[row]
            fid_text = "" if err.get("fid") is None else str(err["fid"])
            values = [
                fid_text,
                err.get("attribute", ""),
                err.get("value", ""),
                err.get("message", ""),
                err.get("expr", ""),
            ]
            for col, value in enumerate(values):
                item = QtWidgets.QTableWidgetItem(str(value))
                self.errors_table.setItem(row, col, item)
        self.errors_table.setUpdatesEnabled(True)

        self._errors_render_index = end
        if end < total:
            QTimer.singleShot(0, self._render_errors_table_batch)
            return
        self._pending_errors_render = []
        self._attr_table_rendered = True
        self._errors_render_done = True
        self._finish_post_render_if_ready()

    def _render_topology_table(self, topology_errors):
        self._topology_errors = topology_errors
        total = len(topology_errors)
        start, end = self._update_topology_pagination_ui(total)
        self._visible_topology_errors = list(topology_errors[start:end])
        self._pending_topology_render = list(self._visible_topology_errors)
        self._topology_render_index = 0
        self.topology_table.clearContents()
        self.topology_table.setRowCount(len(self._pending_topology_render))
        self.topology_table_info_label.setText("Topološke napake")
        if not self._pending_topology_render:
            self._topology_table_rendered = True
            self._topology_render_done = True
            self._finish_post_render_if_ready()
            return
        QTimer.singleShot(0, self._render_topology_table_batch)


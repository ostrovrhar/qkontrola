    @staticmethod
    def _geometry_family_for_layer(layer):
        if layer is None:
            return "unknown"
        try:
            geom_type = layer.geometryType()
        except Exception:
            return "unknown"
        try:
            if geom_type == Qgis.GeometryType.Point:
                return "point"
            if geom_type == Qgis.GeometryType.Line:
                return "line"
            if geom_type == Qgis.GeometryType.Polygon:
                return "polygon"
        except Exception:
            pass
        try:
            geom_type_int = int(geom_type)
            if geom_type_int == 0:
                return "point"
            if geom_type_int == 1:
                return "line"
            if geom_type_int == 2:
                return "polygon"
        except Exception:
            pass
        return "unknown"

    def _selected_topology_checks(self, layer=None, relevant_only=False):
        family = self._geometry_family_for_layer(layer)
        selected = {}
        for key, _label, _count_key, families in self._topology_rule_defs():
            if relevant_only and family not in families:
                selected[key] = False
                continue
            selected[key] = bool(self.topology_settings.get(key, False))
        return selected

    @staticmethod
    def _topology_family_from_stats(topo_stats, fallback_family="unknown"):
        if topo_stats.get("polygon_layer"):
            return "polygon"
        if topo_stats.get("line_layer"):
            return "line"
        if fallback_family in {"point", "line", "polygon"}:
            return fallback_family
        if topo_stats.get("enabled"):
            # If topology was enabled and not line/polygon, treat as point layer.
            return "point"
        return "unknown"

    def _open_topology_settings_dialog(self):
        layer = self.layer_combo.currentLayer()
        if layer is None:
            QtWidgets.QMessageBox.information(
                self,
                "QKontrola",
                "Najprej izberi sloj, nato odpri nastavitve topoloških kontrol.",
            )
            return
        family = self._geometry_family_for_layer(layer)
        dialog = QtWidgets.QDialog(self)
        dialog.setWindowTitle("Nastavitve topoloških kontrol")
        dialog.setModal(True)
        layout = QtWidgets.QVBoxLayout(dialog)

        family_label = {
            "point": "točkovni sloj",
            "line": "linijski sloj",
            "polygon": "poligonski sloj",
        }.get(family, "izbrani sloj")
        info_label = QtWidgets.QLabel(f"Kontrole za: {family_label}.")
        info_label.setStyleSheet("color: #4b5563;")
        layout.addWidget(info_label)

        checks = [
            (key, label)
            for key, label, _count_key, families in self._topology_rule_defs()
            if family in families
        ]
        if not checks:
            QtWidgets.QMessageBox.information(
                self,
                "QKontrola",
                "Za izbrani sloj ni na voljo topoloških kontrol.",
            )
            return

        widgets = {}
        for key, label in checks:
            cb = QtWidgets.QCheckBox(label)
            cb.setChecked(bool(self.topology_settings.get(key, False)))
            layout.addWidget(cb)
            widgets[key] = cb

        buttons = QtWidgets.QDialogButtonBox(
            QtWidgets.QDialogButtonBox.StandardButton.Ok
            | QtWidgets.QDialogButtonBox.StandardButton.Cancel
        )
        buttons.accepted.connect(dialog.accept)
        buttons.rejected.connect(dialog.reject)
        layout.addWidget(buttons)

        if dialog.exec() != QtWidgets.QDialog.DialogCode.Accepted:
            return

        for key, cb in widgets.items():
            self.topology_settings[key] = cb.isChecked()

        if self.enable_topology_cb.isChecked() and not any(
            self._selected_topology_checks(layer=layer, relevant_only=True).values()
        ):
            QtWidgets.QMessageBox.information(
                self,
                "QKontrola",
                "Topološke kontrole so vključene, vendar ni izbrano nobeno pravilo.",
            )


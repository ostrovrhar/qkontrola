        cond_feature_errors = [e for e in errors if e.get("_cond")]
        schema_errors = [e for e in errors if e.get("fid") is None]
        topo_errors = result.get("topology_errors", [])
        cond_rule_count = int(result.get("conditional_rule_count", 0))

        attr_err_by_fid = {}
        for err in attr_feature_errors:
            fid = err.get("fid")
            if fid is None:
                continue
            attr_err_by_fid[fid] = attr_err_by_fid.get(fid, 0) + 1
        cond_err_by_fid = {}
        for err in cond_feature_errors:
            fid = err.get("fid")
            if fid is None:
                continue
            cond_err_by_fid[fid] = cond_err_by_fid.get(fid, 0) + 1
        topo_err_by_fid = {}
        for err in topo_errors:
            fid = err.get("fid")
            if fid is None:
                continue
            topo_err_by_fid[fid] = topo_err_by_fid.get(fid, 0) + 1

        with open(path, "w", newline="", encoding="utf-8") as handle:
            writer = csv.writer(handle)
            writer.writerow(["SECTION", "KEY", "VALUE"])
            writer.writerow(["meta", "layer", self._last_layer_name])
            writer.writerow(["meta", "csv_rules", self._current_task_csv_path])
            writer.writerow(["summary", "objects", result.get("total_features", 0)])
            writer.writerow(
                ["summary", "attribute_feature_errors", len(attr_feature_errors)]
            )
            writer.writerow(["summary", "schema_csv_errors", len(schema_errors)])
            writer.writerow(["summary", "dependency_rule_count", cond_rule_count])
            writer.writerow(["summary", "dependency_errors", len(cond_feature_errors)])
            writer.writerow(["summary", "topology_errors", len(topo_errors)])
            writer.writerow(
                [
                    "summary",
                    "attr_objects_with_1_error",
                    sum(1 for n in attr_err_by_fid.values() if n == 1),
                ]
            )
            writer.writerow(
                [
                    "summary",
                    "attr_objects_with_multiple_errors",
                    sum(1 for n in attr_err_by_fid.values() if n > 1),
                ]
            )
            writer.writerow(
                [
                    "summary",
                    "dep_objects_with_1_error",
                    sum(1 for n in cond_err_by_fid.values() if n == 1),
                ]
            )
            writer.writerow(
                [
                    "summary",
                    "dep_objects_with_multiple_errors",
                    sum(1 for n in cond_err_by_fid.values() if n > 1),
                ]
            )
            writer.writerow(
                [
                    "summary",
                    "topo_objects_with_1_error",
                    sum(1 for n in topo_err_by_fid.values() if n == 1),
                ]
            )
            writer.writerow(
                [
                    "summary",
                    "topo_objects_with_multiple_errors",
                    sum(1 for n in topo_err_by_fid.values() if n > 1),
                ]
            )
            writer.writerow([])

            writer.writerow(
                [
                    "ATTR_STATS",
                    "attribute",
                    "rule_type",
                    "param",
                    "field_type",
                    "exists",
                    "type_ok",
                    "checked",
                    "failed",
                ]
            )
            for stat in result.get("attr_stats", []):
                writer.writerow(
                    [
                        "attr",
                        stat.get("attribute", ""),
                        stat.get("rule_type", ""),
                        stat.get("param", ""),
                        stat.get("field_type", ""),
                        "DA" if stat.get("exists", True) else "NE",
                        "DA" if stat.get("type_ok", True) else "NE",
                        stat.get("checked", 0),
                        stat.get("failed", 0),
                    ]
                )
            writer.writerow([])

            writer.writerow(["TOPO_STATS", "rule", "checked_features", "violations"])
            for enabled_key, label, count_key, families in self._topology_rule_defs():
                if report_family not in families:
                    continue
                if topo_stats.get(enabled_key):
                    writer.writerow(
                        [
                            "topo",
                            label,
                            topo_stats.get("checked_features", 0),
                            topo_stats.get(count_key, 0),
                        ]
                    )

        self._set_status_export_message("Poročilo izvoženo v CSV", path)


    def _load_rules(self, csv_path):
        rules = []
        load_errors = []
        valid_types = {
            "dovoljene vrednosti",
            "regex",
            "ne sme biti prazno",
            "mora biti prazno",
        }
        with open(csv_path, newline="", encoding="utf-8-sig") as handle:
            reader = csv.DictReader(handle)
            if reader.fieldnames is None:
                raise ValueError("CSV je prazen.")
            reader.fieldnames = [h.strip() if h else h for h in reader.fieldnames]
            col_names = [h for h in reader.fieldnames if h]
            has_field_type = "TARGET_FIELD_TYPE" in col_names
            if (
                "TARGET_FIELD" not in col_names
                or "TARGET_FIELD_RULE" not in col_names
                or "TARGET_FIELD_RULE_PARAM" not in col_names
            ):
                raise ValueError(
                    "CSV za kontrolo vrednosti mora vsebovati stolpce: TARGET_FIELD, TARGET_FIELD_RULE, TARGET_FIELD_RULE_PARAM. "
                    f"Dobljeni: {', '.join(col_names)}"
                )
            for i, row in enumerate(reader, start=2):
                target = (row.get("TARGET_FIELD") or "").strip()
                if not target or target.startswith(";"):
                    continue
                rule_type = (row.get("TARGET_FIELD_RULE") or "").strip()
                param = (row.get("TARGET_FIELD_RULE_PARAM") or "").strip()
                field_type = (
                    (row.get("TARGET_FIELD_TYPE") or "").strip()
                    if has_field_type
                    else ""
                )
                if not rule_type:
                    continue
                if rule_type not in valid_types:
                    load_errors.append(
                        {
                            "fid": None,
                            "attribute": target,
                            "value": "",
                            "message": f"CSV vrstica {i}: neznan tip pravila '{rule_type}'.",
                            "expr": "",
                        }
                    )
                    continue
                rules.append(ValidationRule(i, target, rule_type, param, field_type))
        self._last_csv_data_rows = len(rules)
        return rules, load_errors

    @staticmethod
    def _load_conditional_rules(csv_path):
        rules = []
        with open(csv_path, newline="", encoding="utf-8-sig") as handle:
            reader = csv.DictReader(handle)
            if reader.fieldnames is None:
                raise ValueError("CSV je prazen.")
            reader.fieldnames = [h.strip() if h else h for h in reader.fieldnames]
            col_names = [h for h in reader.fieldnames if h]
            required_cols = {
                "TARGET_FIELD",
                "TARGET_FIELD_RULE",
                "TARGET_FIELD_RULE_PARAM",
                "CONDITION_FIELD",
                "CONDITION_FIELD_VALUE",
            }
            if not required_cols.issubset(col_names):
                raise ValueError(
                    "CSV za pogojne odvisnosti mora vsebovati stolpce: TARGET_FIELD, TARGET_FIELD_RULE, TARGET_FIELD_RULE_PARAM, CONDITION_FIELD, CONDITION_FIELD_VALUE. "
                    f"Dobljeni: {', '.join(col_names)}"
                )
            for i, row in enumerate(reader, start=2):
                target = (row.get("TARGET_FIELD") or "").strip()
                if not target or target.startswith(";"):
                    continue
                rule_type = (row.get("TARGET_FIELD_RULE") or "").strip()
                param = (row.get("TARGET_FIELD_RULE_PARAM") or "").strip()
                cond_field = (row.get("CONDITION_FIELD") or "").strip()
                cond_value_raw = (row.get("CONDITION_FIELD_VALUE") or "").strip()
                if not rule_type or not cond_field or not cond_value_raw:
                    continue
                # Parse COND_VALUE: split by |, handle negation prefix ¬
                parts = cond_value_raw.split("|")
                cleaned = []
                all_negated = True
                for p in parts:
                    p = p.strip()
                    if not p:
                        continue
                    if p.startswith("\u00ac"):
                        cleaned.append(p[1:].strip())
                    else:
                        cleaned.append(p)
                        all_negated = False
                if not cleaned:
                    continue
                rules.append(
                    ConditionalRule(
                        i,
                        target,
                        rule_type,
                        param,
                        cond_field,
                        cond_value_raw,
                        cleaned,
                        all_negated,
                    )
                )
        return rules


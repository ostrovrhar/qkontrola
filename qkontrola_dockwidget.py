    def _export_errors_csv(self, error_rows, error_type, default_name):
        if not error_rows:
            QtWidgets.QMessageBox.information(
                self,
                "QKontrola",
                "Ni napak za izvoz.",
            )
            return

        path, _ = QtWidgets.QFileDialog.getSaveFileName(
            self,
            "Izvozi seznam napak v CSV",
            self._default_save_target(default_name),
            "CSV (*.csv)",
        )
        if not path:
            return
        if not path.lower().endswith(".csv"):
            path += ".csv"
        if not self._can_overwrite_path(path):
            QtWidgets.QMessageBox.warning(
                self,
                "QKontrola",
                "CSV datoteka je trenutno odprta ali zaščitena za pisanje. Zapri datoteko in poskusi znova.",
            )
            return
        self._save_last_save_dir(path)

        try:
            with open(path, "w", newline="", encoding="utf-8") as handle:
                writer = csv.writer(handle)
                if error_type == "attribute":
                    writer.writerow(["fid", "attribute", "value", "message", "expr"])
                    for err in error_rows:
                        writer.writerow(
                            [
                                err.get("fid", ""),
                                err.get("attribute", ""),
                                err.get("value", ""),
                                err.get("message", ""),
                                err.get("expr", ""),
                            ]
                        )
                else:
                    writer.writerow(["fid", "check", "message"])
                    for err in error_rows:
                        writer.writerow(
                            [
                                err.get("fid", ""),
                                err.get("check", ""),
                                err.get("message", ""),
                            ]
                        )
        except OSError as exc:
            QtWidgets.QMessageBox.critical(
                self,
                "QKontrola",
                f"Izvoz CSV ni uspel:\n{exc}",
            )
            return

        self._set_status_export_message("Izvoz CSV uspešen", path)

    def _export_errors_gpkg(self, error_rows, error_type, default_name):
        if self._current_task and self._current_task.isActive():
            QtWidgets.QMessageBox.information(
                self,
                "QKontrola",
                "Kontrola trenutno teče. Počakaj na zaključek ali jo prekini.",
            )
            return
        if self._post_render_active:
            QtWidgets.QMessageBox.information(
                self,
                "QKontrola",
                "Počakaj, da se izpis rezultatov zaključi.",
            )
            return
        if self._export_in_progress or (
            self._current_export_task and self._current_export_task.isActive()
        ):
            QtWidgets.QMessageBox.information(
                self,
                "QKontrola",
                "Izvoz napak že teče. Počakaj ali ga prekini.",
            )
            return

        if not error_rows:
            QtWidgets.QMessageBox.information(
                self,
                "QKontrola",
                "Ni napak za izvoz.",
            )
            return

        layer = self.layer_combo.currentLayer()
        if layer is None:
            QtWidgets.QMessageBox.warning(
                self,
                "QKontrola",
                "Izberi sloj.",
            )
            return
        no_geom = False
        try:
            no_geom = layer.wkbType() == Qgis.WkbType.NoGeometry
        except Exception:
            no_geom = layer.wkbType() == QgsWkbTypes.NoGeometry
        if no_geom:
            QtWidgets.QMessageBox.warning(
                self,
                "QKontrola",
                "Izbrani sloj nima geometrije, zato izvoz v GPKG ni mogoč.",
            )
            return

        path, _ = QtWidgets.QFileDialog.getSaveFileName(
            self,
            "Izvozi seznam napak v GPKG",
            self._default_save_target(default_name),
            "GeoPackage (*.gpkg)",
        )
        if not path:
            return
        if not path.lower().endswith(".gpkg"):
            path += ".gpkg"
        if not self._can_overwrite_path(path):
            QtWidgets.QMessageBox.warning(
                self,
                "QKontrola",
                "GPKG datoteka je trenutno odprta ali zaščitena za pisanje. Zapri datoteko in poskusi znova.",
            )
            return
        self._save_last_save_dir(path)

        task = GpkgExportTask(
            layer_source=layer.source(),
            layer_provider=layer.providerType(),
            layer_crs_wkt=layer.crs().toWkt(),
            transform_context=QgsProject.instance().transformContext(),
            error_rows=error_rows,
            error_type=error_type,
            output_path=path,
        )
        self._start_export_task(task, error_type)

    def _start_export_task(self, task, error_type):
        self._current_export_task = task
        self._current_export_task_kind = error_type
        self._export_in_progress = True
        self.progress_bar.setVisible(True)
        self.progress_bar.setRange(0, 100)
        self.progress_bar.setValue(0)
        self.status_label.setText("Izvoz GPKG teče ...")

        self.cancel_btn.setEnabled(True)
        self.run_btn.setEnabled(False)
        self._set_controls_enabled_for_export(False)

        task.progressChanged.connect(self._on_export_task_progress)
        task.taskCompleted.connect(self._on_export_task_completed)
        task.taskTerminated.connect(self._on_export_task_terminated)
        QgsApplication.taskManager().addTask(task)
        self._update_run_button_state()

    def _finish_export_task_ui(self):
        self.cancel_btn.setEnabled(False)
        self._export_in_progress = False
        self.progress_bar.setVisible(False)
        self.progress_bar.setRange(0, 100)
        self.progress_bar.setValue(0)
        self._set_controls_enabled_for_export(True)
        self._update_run_button_state()

    def _on_export_task_progress(self, progress):
        self.progress_bar.setValue(int(progress))

    def _on_export_task_completed(self):
        task = self._current_export_task
        self._finish_export_task_ui()
        if not task:
            return
        result = task.result_data or {}
        path = result.get("path", "")
        missing_geom_count = int(result.get("missing_geom_count", 0))
        exported_count = int(result.get("exported_count", 0))
        note = ""
        if missing_geom_count > 0:
            note = f" ({missing_geom_count} zapisov brez geometrije ni bilo izvoženih)"
        self._set_status_export_message(
            f"Izvoz GPKG uspešen: {exported_count} zapisov{note}",
            path,
        )
        self._current_export_task = None
        self._current_export_task_kind = ""

    def _on_export_task_terminated(self):
        task = self._current_export_task
        self._finish_export_task_ui()
        if task and task.isCanceled():
            self.status_label.setText("Izvoz GPKG je prekinjen.")
        else:
            message = task.error_message if task else "Neznana napaka."
            self.status_label.setText("Izvoz GPKG se je končal z napako.")
            QtWidgets.QMessageBox.critical(
                self, "QKontrola", f"Izvoz GPKG ni uspel:\n{message}"
            )
        self._current_export_task = None
        self._current_export_task_kind = ""

    def closeEvent(self, event):
        self._clear_topology_gap_highlight()
        layer = getattr(self, "_selection_signal_layer", None)
        if layer is not None:
            try:
                layer.selectionChanged.disconnect(self._on_layer_selection_changed)
            except Exception:
                pass
            self._selection_signal_layer = None
        if self._current_task and self._current_task.isActive():
            self._current_task.cancel()
        if self._current_export_task and self._current_export_task.isActive():
            self._current_export_task.cancel()
        self.closing_plugin.emit()
        event.accept()
